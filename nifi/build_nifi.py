"""Generates the NiFi side of the LM -> FMS locations POC:

  python_extensions/LmFmsLocations.py  - p9 UDF core sliced verbatim + NiFi Python processors
  LM_To_FMS_Locations.flow.json        - flow definition (Process Group > Upload flow definition)

Re-run after any change to the Fabric UDF so the NiFi copy stays in parity:
  python3 nifi/build_nifi.py
"""
import json
import os
import uuid
from pathlib import Path

HERE = Path(__file__).resolve().parent
# The Fabric UDF lives in the MTCIntegrations repo; default assumes it is a sibling folder.
MTC_REPO = Path(os.environ.get("MTC_REPO", HERE.parents[1] / "MTCIntegrations")).resolve()
UDF = MTC_REPO / "Fabric-Mtc-Integrations" / "9 - LM_To_FMS_Locations" / \
    "udf_lm_fms_locations.UserDataFunction" / "function_app.py"

NIFI_VERSION = "2.4.0"   # bundle versions; NiFi re-binds to the installed version if only one exists
PY_VERSION = "0.1.0"     # ProcessorDetails.version in processors_template.py


# ------------------------------------------------------------ python extension

def build_extension():
    lines = UDF.read_text().splitlines()
    start_fabric = next(i for i, l in enumerate(lines) if l.startswith("import fabric.functions"))
    start_core = next(i for i, l in enumerate(lines) if l.startswith("_TS_FMT = "))
    end_core = next(i for i, l in enumerate(lines) if "-- entry points" in l)
    core = lines[:start_fabric] + [""] + lines[start_core:end_core]
    header = ['# GENERATED by build_nifi.py from %s -- do not edit; edit the UDF or processors_template.py.'
              % UDF.relative_to(MTC_REPO)]
    out = HERE / "python_extensions" / "LmFmsLocations.py"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(header + core) + (HERE / "processors_template.py").read_text())
    return out


# ------------------------------------------------------------------ flow JSON

def _id(name):
    return str(uuid.uuid5(uuid.NAMESPACE_URL, "mtc/lm2fms/" + name))


PG = _id("pg")


def bundle(artifact, version=NIFI_VERSION):
    return {"group": "org.apache.nifi", "artifact": artifact, "version": version}


STD = bundle("nifi-standard-nar")
UPD = bundle("nifi-update-attribute-nar")
MAIL = bundle("nifi-email-nar")
PYB = bundle("python-extensions", PY_VERSION)
API = bundle("nifi-standard-services-api-nar")

processors, connections, services, labels = [], [], [], []
_by_name = {}


def service(name, type_, bndl, api, props, sensitive=()):
    s = {"identifier": _id("cs/" + name), "name": name, "comments": "", "type": type_, "bundle": bndl,
         "properties": props,
         "propertyDescriptors": {p: {"name": p, "displayName": p, "identifiesControllerService": False,
                                     "sensitive": True, "dynamic": False} for p in sensitive},
         "controllerServiceApis": [{"type": api, "bundle": API}],
         "scheduledState": "DISABLED", "bulletinLevel": "WARN",
         "componentType": "CONTROLLER_SERVICE", "groupIdentifier": PG}
    services.append(s)
    return s["identifier"]


def proc(name, type_, bndl, x, y, props=None, auto=(), sched="0 sec", tasks=1, comments="",
         service_props=(), sensitive=(), penalty="30 sec", node="ALL", strategy="TIMER_DRIVEN",
         retry=(), retries=10):
    descriptors = {p: {"name": p, "displayName": p, "identifiesControllerService": True,
                       "sensitive": False, "dynamic": False} for p in service_props}
    descriptors.update({p: {"name": p, "displayName": p, "identifiesControllerService": False,
                            "sensitive": True, "dynamic": False} for p in sensitive})
    p = {"identifier": _id("p/" + name), "name": name, "comments": comments,
         "position": {"x": x, "y": y}, "type": type_, "bundle": bndl,
         "properties": props or {}, "propertyDescriptors": descriptors, "style": {},
         "schedulingPeriod": sched, "schedulingStrategy": strategy, "executionNode": node,
         "penaltyDuration": penalty, "yieldDuration": "1 sec", "bulletinLevel": "WARN",
         "runDurationMillis": 0, "concurrentlySchedulableTaskCount": tasks,
         "autoTerminatedRelationships": list(auto), "scheduledState": "ENABLED",
         "retryCount": retries, "retriedRelationships": list(retry), "backoffMechanism": "PENALIZE_FLOWFILE",
         "maxBackoffPeriod": "10 mins", "componentType": "PROCESSOR", "groupIdentifier": PG}
    processors.append(p)
    _by_name[name] = p
    return name


def _end(name):
    return {"id": _by_name[name]["identifier"], "type": "PROCESSOR", "groupId": PG, "name": name, "comments": ""}


def connect(src, dst, *rels):
    connections.append({
        "identifier": _id("c/%s/%s/%s" % (src, dst, ",".join(rels))), "name": "",
        "source": _end(src), "destination": _end(dst), "labelIndex": 1, "zIndex": 0,
        "selectedRelationships": list(rels), "backPressureObjectThreshold": 10000,
        "backPressureDataSizeThreshold": "1 GB", "flowFileExpiration": "0 sec", "prioritizers": [],
        "bends": [], "loadBalanceStrategy": "DO_NOT_LOAD_BALANCE", "partitioningAttribute": "",
        "loadBalanceCompression": "DO_NOT_COMPRESS", "componentType": "CONNECTION", "groupIdentifier": PG})


def label(text, x, y, w=420, h=60):
    labels.append({"identifier": _id("l/" + text), "label": text, "position": {"x": x, "y": y},
                   "width": w, "height": h, "zIndex": 0, "style": {"font-size": "14px"},
                   "componentType": "LABEL", "groupIdentifier": PG})


def build_flow():
    lm_db = service("LocationManagement DB", "org.apache.nifi.dbcp.DBCPConnectionPool",
                    bundle("nifi-dbcp-service-nar"), "org.apache.nifi.dbcp.DBCPService", {
                        "Database Connection URL": "#{lm_jdbc_url}",
                        "Database Driver Class Name": "com.microsoft.sqlserver.jdbc.SQLServerDriver",
                        "database-driver-locations": "#{jdbc_driver_dir}",
                        "Database User": "#{lm_db_user}",
                        "Password": "#{lm_db_password}",
                        "Max Total Connections": "2"}, sensitive=["Password"])
    fms_db = service("FMS DB2", "org.apache.nifi.dbcp.DBCPConnectionPool",
                     bundle("nifi-dbcp-service-nar"), "org.apache.nifi.dbcp.DBCPService", {
                         "Database Connection URL": "#{fms_jdbc_url}",
                         "Database Driver Class Name": "com.ibm.as400.access.AS400JDBCDriver",
                         "database-driver-locations": "#{jdbc_driver_dir}",
                         "Database User": "#{fms_db_user}",
                         "Password": "#{fms_db_password}",
                         "Max Total Connections": "#{fms_parallelism}"}, sensitive=["Password"])
    writer = service("JSON array writer", "org.apache.nifi.json.JsonRecordSetWriter",
                     bundle("nifi-record-serialization-services-nar"),
                     "org.apache.nifi.serialization.RecordSetWriterFactory", {
                         "Schema Write Strategy": "no-schema",
                         "schema-access-strategy": "inherit-record-schema",
                         "output-grouping": "output-array",
                         "Pretty Print JSON": "false",
                         "suppress-nulls": "never-suppress"})

    mail_props = {"SMTP Hostname": "#{mail_host}", "SMTP Port": "#{mail_port}", "SMTP Auth": "true",
                  "SMTP Username": "#{mail_username}", "SMTP Password": "#{mail_password}",
                  "SMTP TLS": "true", "From": "#{mail_from}", "To": "#{mail_to}"}

    X, X2, X3 = 0, 520, 1040
    proc("Schedule", "org.apache.nifi.processors.standard.GenerateFlowFile", STD, X, 0,
         {"File Size": "0B", "Batch Size": "1"}, sched="0 0/15 9-16 * * ?", strategy="CRON_DRIVEN",
         node="PRIMARY",
         comments="Fabric pipeline trigger: every 15 min, 09:00-16:45 (Quartz cron). Primary node only.")
    proc("ReadWatermark", "ComputeLmWindow", PYB, X, 200,
         {"Staging Directory": "#{staging_dir}", "Override Begin Ts": "#{override_begin_ts}",
          "Max Locations Per Run": "#{max_locations_per_run}"}, auto=["original"],
         comments="readWatermark + CheckWatermarkError")
    proc("LookupLocationChanges", "org.apache.nifi.processors.standard.ExecuteSQLRecord", STD, X, 400,
         {"Database Connection Pooling Service": lm_db,
          "SQL select query": (HERE / "lm-query.sql").read_text(),
          "esqlrecord-record-writer": writer, "Max Wait Time": "20 min"},
         service_props=["Database Connection Pooling Service", "esqlrecord-record-writer"],
         retry=["failure"], retries=5,
         comments="Fabric LookupLocationChanges: timeout 20 min, 5 retries 30 s apart (penalty).")
    proc("DropSqlArgs", "org.apache.nifi.processors.attributes.UpdateAttribute", UPD, X, 600,
         {"Delete Attributes Expression": "sql\\.args\\..*"},
         comments="ExecuteSQL would bind leftover sql.args.* into the DB2 block.")
    proc("BuildLocationCalls", "BuildFmsLocationCalls", PYB, X, 800,
         {"FMS Library": "#{fms_library}", "Default Contact Phone": "#{default_contact_phone}",
          "Max Locations Per Run": "#{max_locations_per_run}"}, auto=["original"],
         comments="buildLocationCalls + CheckBuildError; 'empty' skips the DB2 fan-out.")
    proc("SplitPerLocation", "org.apache.nifi.processors.standard.SplitJson", STD, X, 1000,
         {"JsonPath Expression": "$.*"}, auto=["original"])
    proc("ExtractCall", "org.apache.nifi.processors.standard.EvaluateJsonPath", STD, X, 1200,
         {"Destination": "flowfile-attribute", "Return Type": "auto-detect",
          "lm.locationId": "$.locationId", "lm.requirementCount": "$.requirementCount", "lm.sql": "$.sql"})
    proc("CallFmsLocation", "org.apache.nifi.processors.standard.ExecuteSQL", STD, X, 1400,
         {"Database Connection Pooling Service": fms_db, "SQL select query": "${lm.sql}",
          "Max Wait Time": "3 min"},
         service_props=["Database Connection Pooling Service"], tasks=12, penalty="0 sec",
         comments="Always ends on 'failure': the block SIGNALs P9OK/P9ERR and executesql.error.message "
                  "carries the outcome. Same trick as the Fabric Lookup. Timeout 3 min, no retry "
                  "(Fabric CallFmsLocation); a timeout lands on 'failure' and is classed technical.")
    proc("RecordLocationOutcome", "org.apache.nifi.processors.standard.AttributesToJSON", STD, X, 1600,
         {"Attributes List": "lm.locationId,lm.requirementCount,executesql.error.message",
          "Destination": "flowfile-content", "Include Core Attributes": "false", "Null Value": "false"})
    proc("GatherOutcomes", "org.apache.nifi.processors.standard.MergeContent", STD, X, 1800,
         {"Merge Strategy": "Defragment", "Merge Format": "Binary Concatenation",
          "Attribute Strategy": "Keep Only Common Attributes", "Delimiter Strategy": "Text",
          "Header File": "[", "Footer File": "]", "Demarcator File": ",", "Max Bin Age": "20 min"},
         auto=["original"], comments="Reassembles the SplitJson fragments; a lost fragment ages out to failure.")
    proc("FinalizeLocations", "FinalizeLmLocations", PYB, X, 2000, {}, auto=["original"])
    proc("WriteItemLog", "org.apache.nifi.processors.standard.PutFile", STD, X2, 2000,
         {"Directory": "#{staging_dir}/items/${lm.runId}", "Conflict Resolution Strategy": "replace",
          "Create Missing Directories": "true"}, auto=["success"])
    proc("AdvanceWatermark", "AdvanceLmWatermark", PYB, X, 2200,
         {"Staging Directory": "#{staging_dir}"}, auto=["original"])
    proc("CheckDigestEmail", "org.apache.nifi.processors.standard.RouteOnAttribute", STD, X2, 2200,
         {"Routing Strategy": "Route to Property name", "has_failures": "${lm.hasFailures:equals('true')}"},
         auto=["unmatched"])
    proc("SendDigestEmail", "org.apache.nifi.processors.standard.PutEmail", MAIL, X2, 2400,
         dict(mail_props, **{
             "Subject": "BUSINESS: NiFi: lm-to-fms-locations - ${lm.fmsErrors} location(s) refused by FMS - run ${lm.runId}",
             "Message": "${lm.digestBody}"}),
         auto=["success", "failure"], sensitive=["SMTP Password"])
    proc("MarkSucceeded", "org.apache.nifi.processors.attributes.UpdateAttribute", UPD, X, 2400,
         {"lm.status": "Succeeded"})

    proc("MarkFailed", "org.apache.nifi.processors.attributes.UpdateAttribute", UPD, X3, 1200,
         {"lm.status": "Failed",
          "lm.error": "${lm.error:replaceEmpty(${executesql.error.message:replaceEmpty('see bulletins')})}"},
         comments="Every structural failure lands here: the watermark is never advanced on this path.")
    proc("SendUpstreamFailureEmail", "org.apache.nifi.processors.standard.PutEmail", MAIL, X3, 1400,
         dict(mail_props, **{
             "Subject": "ERROR: NiFi: lm-to-fms-locations FAILED (watermark held) - run ${lm.runId}",
             "Message": "lm-to-fms-locations failed before the watermark was advanced. Some locations may "
                        "already have reached FMS.\n\nRun: ${lm.runId}\nWindow: ${lm.beginTs} .. ${lm.endTs}\n"
                        "Reason: ${lm.error}\n\nThe watermark was NOT advanced -- this window will be re-read."}),
         auto=["success", "failure"], sensitive=["SMTP Password"])

    proc("BuildRunLog", "org.apache.nifi.processors.standard.AttributesToJSON", STD, X2, 2600,
         {"Attributes Regular Expression": "lm\\.(?!sql|digestBody|skippedJson).*",
          "Destination": "flowfile-content", "Include Core Attributes": "false"},
         auto=["failure"], comments="InvokeLogging equivalent, on both success and failure paths.")
    proc("NameRunLog", "org.apache.nifi.processors.attributes.UpdateAttribute", UPD, X2, 2800,
         {"filename": "${lm.runId}.json"})
    proc("WriteRunLog", "org.apache.nifi.processors.standard.PutFile", STD, X2, 3000,
         {"Directory": "#{staging_dir}/runlog", "Conflict Resolution Strategy": "replace",
          "Create Missing Directories": "true"}, auto=["success", "failure"])

    connect("Schedule", "ReadWatermark", "success")
    connect("ReadWatermark", "LookupLocationChanges", "success")
    connect("LookupLocationChanges", "DropSqlArgs", "success")
    connect("DropSqlArgs", "BuildLocationCalls", "success")
    connect("BuildLocationCalls", "SplitPerLocation", "success")
    connect("BuildLocationCalls", "FinalizeLocations", "empty")
    connect("SplitPerLocation", "ExtractCall", "split")
    connect("ExtractCall", "CallFmsLocation", "matched")
    connect("CallFmsLocation", "RecordLocationOutcome", "success", "failure")
    connect("RecordLocationOutcome", "GatherOutcomes", "success")
    connect("GatherOutcomes", "FinalizeLocations", "merged")
    connect("FinalizeLocations", "WriteItemLog", "success")
    connect("FinalizeLocations", "AdvanceWatermark", "success")
    connect("AdvanceWatermark", "CheckDigestEmail", "success")
    connect("AdvanceWatermark", "MarkSucceeded", "success")
    connect("CheckDigestEmail", "SendDigestEmail", "has_failures")
    connect("MarkSucceeded", "BuildRunLog", "success")
    for src, rels in [("ReadWatermark", ["failure"]), ("LookupLocationChanges", ["failure"]),
                      ("BuildLocationCalls", ["failure"]), ("SplitPerLocation", ["failure"]),
                      ("ExtractCall", ["unmatched", "failure"]), ("RecordLocationOutcome", ["failure"]),
                      ("GatherOutcomes", ["failure"]), ("FinalizeLocations", ["failure"]),
                      ("WriteItemLog", ["failure"]), ("AdvanceWatermark", ["failure"])]:
        connect(src, "MarkFailed", *rels)
    connect("MarkFailed", "SendUpstreamFailureEmail", "success")
    connect("MarkFailed", "BuildRunLog", "success")
    connect("BuildRunLog", "NameRunLog", "success")
    connect("NameRunLog", "WriteRunLog", "success")

    label("LM -> FMS locations (port of Fabric 9_pl_LM_To_FMS_Locations). Processor names = Fabric activity names.",
          X - 20, -100, 900, 50)

    params = [
        ("staging_dir", "/opt/nifi/data/lm2fms", False, "watermark.json, items/, runlog/"),
        ("override_begin_ts", "", False, "yyyy-MM-dd HH:mm:ss.SSS to replay; blank = normal"),
        ("max_locations_per_run", "400", False, ""),
        ("fms_library", "FMSLIB", False, ""),
        ("default_contact_phone", "0000000001", False, ""),
        ("fms_parallelism", "12", False, "DB2 pool size; match CallFmsLocation concurrent tasks"),
        ("jdbc_driver_dir", "/opt/nifi/drivers", False, "Folder with mssql-jdbc and jt400 jars"),
        ("lm_jdbc_url", "jdbc:sqlserver://HOST:1433;databaseName=LocationManagement;encrypt=true", False, ""),
        ("lm_db_user", "", False, ""), ("lm_db_password", None, True, ""),
        ("fms_jdbc_url", "jdbc:as400://HOST;naming=system;prompt=false", False, ""),
        ("fms_db_user", "", False, ""), ("fms_db_password", None, True, ""),
        ("mail_host", "smtp.sendgrid.net", False, ""), ("mail_port", "587", False, ""),
        ("mail_username", "apikey", False, ""), ("mail_password", None, True, "SendGrid API key"),
        ("mail_from", "noreply@enru.io", False, ""), ("mail_to", "", False, "Support distribution list"),
    ]
    ctx = "lm_to_fms_locations"
    flow = {
        "flowContents": {
            "identifier": PG, "name": "LM_To_FMS_Locations", "comments":
                "Pushes LocationManagement location changes to FMS: watermark window, one DB2 compound "
                "statement per location, item log, digest mail. A proc error is a business outcome.",
            "position": {"x": 0, "y": 0}, "processGroups": [], "remoteProcessGroups": [],
            "processors": processors, "inputPorts": [], "outputPorts": [], "connections": connections,
            "labels": labels, "funnels": [], "controllerServices": services,
            "parameterContextName": ctx, "defaultFlowFileExpiration": "0 sec",
            "defaultBackPressureObjectThreshold": 10000, "defaultBackPressureDataSizeThreshold": "1 GB",
            "flowFileConcurrency": "UNBOUNDED", "flowFileOutboundPolicy": "STREAM_WHEN_AVAILABLE",
            "executionEngine": "INHERITED", "scheduledState": "ENABLED", "maxConcurrentTasks": 1,
            "statelessFlowTimeout": "1 min", "componentType": "PROCESS_GROUP"},
        "externalControllerServices": {},
        "parameterContexts": {ctx: {
            "name": ctx, "description": "LM -> FMS locations POC",
            "parameters": [{"name": n, "description": d, "sensitive": s, "provided": False, "value": v}
                           for n, v, s, d in params],
            "inheritedParameterContexts": [], "componentType": "PARAMETER_CONTEXT"}},
        "flowEncodingVersion": "1.0", "parameterProviders": {}, "latest": False,
    }
    out = HERE / "LM_To_FMS_Locations.flow.json"
    out.write_text(json.dumps(flow, indent=2) + "\n")
    return out


if __name__ == "__main__":
    print(build_extension())
    print(build_flow())
